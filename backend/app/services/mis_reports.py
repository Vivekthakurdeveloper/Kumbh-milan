"""Asynchronous MIS reports and schedules (BE-202).

Reports are generated by the operations worker, stored privately, and downloaded only through an authenticated,
audited endpoint. Rows never include contact details, names, notes, or free text. CSV cells are protected against
spreadsheet formula injection.
"""

