logger = logging.getLogger("kumbh_setu.reports")
J = ReportJobStatus
CONTENT_TYPE = "text/csv"


def _station_for(actor: User, requested: uuid.UUID | None) -> uuid.UUID | None:
    if Role(actor.role) is Role.ADMIN:
        return requested
    if requested is not None and requested != actor.station_id:
        raise ValidationFailed("You can only report on your own station", code="station_scope")
    return actor.station_id


def _validate_period(period_from: datetime, period_to: datetime) -> None:
    if period_to <= period_from:
        raise ValidationFailed("period_to must be after period_from", code="invalid_period")
    if period_to - period_from > timedelta(days=get_settings().report_max_period_days):
        raise ValidationFailed(
            f"Report period cannot exceed {get_settings().report_max_period_days} days", code="invalid_period"
        )


def request_report(
    db: Session,
    actor: User,
    *,
    report_type: ReportType,
    period_from: datetime,
    period_to: datetime,
    station_id: uuid.UUID | None,
    schedule_id: uuid.UUID | None = None,
    commit: bool = True,
) -> ReportJob:
    require_permission(actor, Permission.REPORT_GENERATE)
    _validate_period(period_from, period_to)
    job = ReportJob(
        id=uuid.uuid4(), report_type=report_type, status=J.QUEUED, period_from=period_from, period_to=period_to,
        station_id=_station_for(actor, station_id), requested_by_user_id=actor.id, schedule_id=schedule_id,
    )
    db.add(job)
    record_audit(
        db, action=AuditAction.REPORT_REQUESTED, entity_type="report_job", entity_id=job.id, actor_user_id=actor.id,
        after={"report_type": report_type, "station_id": job.station_id, "period_from": period_from,
               "period_to": period_to, "schedule_id": schedule_id},
    )
    if commit:
        db.commit()
        db.refresh(job)
    return job


def _visible_job(db: Session, actor: User, job_id: uuid.UUID) -> ReportJob:
    require_permission(actor, Permission.REPORT_GENERATE)
    job = db.get(ReportJob, job_id)
    if job is None:
        raise NotFound("Report not found", code="report_not_found")
    if job.requested_by_user_id == actor.id or Role(actor.role) is Role.ADMIN:
        return job
    if job.schedule_id is not None:
        schedule = db.get(ReportSchedule, job.schedule_id)
        if schedule is not None and str(actor.id) in schedule.recipient_user_ids:
            return job
    raise NotFound("Report not found", code="report_not_found")


def get_job(db: Session, actor: User, job_id: uuid.UUID) -> ReportJob:
    return _visible_job(db, actor, job_id)


def list_jobs(db: Session, actor: User, *, limit: int, offset: int) -> tuple[list[ReportJob], int]:
    require_permission(actor, Permission.REPORT_GENERATE)
    conditions = [] if Role(actor.role) is Role.ADMIN else [ReportJob.requested_by_user_id == actor.id]
    total = db.scalar(select(func.count()).select_from(ReportJob).where(*conditions)) or 0
    rows = list(
        db.scalars(
            select(ReportJob).where(*conditions).order_by(ReportJob.created_at.desc(), ReportJob.id)
            .limit(limit).offset(offset)
        )
    )
    return rows, total


def cancel_job(db: Session, storage: ObjectStorage, actor: User, job_id: uuid.UUID) -> ReportJob:
    """Cancels a queued job or revokes a completed artifact (the object is deleted)."""
    job = _visible_job(db, actor, job_id)
    if job.requested_by_user_id != actor.id and Role(actor.role) is not Role.ADMIN:
        raise NotFound("Report not found", code="report_not_found")
    if job.status in (J.CANCELLED, J.EXPIRED, J.FAILED):
        raise Conflict("Report is no longer active", code="report_inactive")
    if job.status == J.RUNNING:
        raise Conflict("Report is being generated; try again shortly", code="report_running")
    if job.storage_key:
        storage.delete(job.storage_key)
    job.status = J.CANCELLED if job.status == J.QUEUED else J.EXPIRED
    record_audit(db, action=AuditAction.REPORT_CANCELLED, entity_type="report_job", entity_id=job.id,
                 actor_user_id=actor.id, after={"status": job.status})
    db.commit()
    db.refresh(job)
    return job


def download(db: Session, storage: ObjectStorage, actor: User, job_id: uuid.UUID) -> tuple[bytes, str]:
    job = _visible_job(db, actor, job_id)
    if job.status != J.COMPLETED or job.storage_key is None:
        raise Conflict("Report is not ready", code="report_not_ready")
    if job.expires_at is not None and job.expires_at <= utcnow():
        raise Gone("Report has expired", code="report_expired")
    body = storage.get(job.storage_key)
    record_audit(db, action=AuditAction.REPORT_DOWNLOADED, entity_type="report_job", entity_id=job.id,
                 actor_user_id=actor.id, after={"report_type": job.report_type, "rows": job.row_count})
    db.commit()
    return body, f"{job.report_type.value.lower()}-{job.period_from:%Y%m%d}-{job.period_to:%Y%m%d}.csv"


# --- Generation ----------------------------------------------------------------------------------


def _case_scope(db: Session, job: ReportJob):
    requester = db.get(User, job.requested_by_user_id)
    conditions = [case_visibility_clause(requester), Case.archived_at.is_(None)]
    if job.station_id is not None:
        conditions.append(Case.station_id == job.station_id)
    return conditions


def _rows(db: Session, job: ReportJob, limit: int) -> tuple[list[str], list[list]]:
    station_codes = dict(db.execute(select(Station.id, Station.code)).all())
    period = (job.period_from, job.period_to)
    if job.report_type is ReportType.CASES:
        header = ["case_number", "case_type", "status", "station", "urgency_level", "assigned", "created_at",
                  "closed_at"]
        rows = db.execute(
            select(Case.case_number, Case.case_type, Case.status, Case.station_id, Case.urgency_level,
                   Case.assigned_to_user_id.is_not(None), Case.created_at, Case.closed_at)
            .where(*_case_scope(db, job), Case.created_at >= period[0], Case.created_at < period[1])
            .order_by(Case.created_at, Case.id).limit(limit)
        ).all()
        return header, [[r[0], r[1], r[2], station_codes.get(r[3]), r[4], r[5], r[6], r[7]] for r in rows]
    if job.report_type is ReportType.REUNIFICATIONS:
        header = ["case_number", "kind", "status", "verification_method", "station", "created_at", "completed_at"]
        rows = db.execute(
            select(Case.case_number, CaseHandover.kind, CaseHandover.status, CaseHandover.verification_method,
                   Case.station_id, CaseHandover.created_at, CaseHandover.completed_at)
            .join(Case, Case.id == CaseHandover.primary_case_id)
            .where(*_case_scope(db, job), CaseHandover.created_at >= period[0], CaseHandover.created_at < period[1])
            .order_by(CaseHandover.created_at, CaseHandover.id).limit(limit)
        ).all()
        return header, [[r[0], r[1], r[2], r[3], station_codes.get(r[4]), r[5], r[6]] for r in rows]
    if job.report_type is ReportType.CUSTODY:
        header = ["case_number", "status", "custody_status", "station", "found_at", "released_at", "created_at"]
        rows = db.execute(
            select(Case.case_number, Case.status, FoundItemDetails.custody_status, Case.station_id,
                   FoundItemDetails.found_at, FoundItemDetails.released_at, Case.created_at)
            .join(FoundItemDetails, FoundItemDetails.case_id == Case.id)
            .where(*_case_scope(db, job), Case.created_at >= period[0], Case.created_at < period[1])
            .order_by(Case.created_at, Case.id).limit(limit)
        ).all()
        return header, [[r[0], r[1], r[2], station_codes.get(r[3]), r[4], r[5], r[6]] for r in rows]
    if job.report_type is ReportType.GRIEVANCES:
        requester = db.get(User, job.requested_by_user_id)
        conditions = [Grievance.created_at >= period[0], Grievance.created_at < period[1]]
        station = job.station_id or (None if Role(requester.role) is Role.ADMIN else requester.station_id)
        if station is not None:
            conditions.append(Grievance.station_id == station)
        header = ["reference", "category", "status", "priority", "station", "escalation_level", "created_at",
                  "due_at", "resolved_at", "closed_at"]
        rows = db.execute(
            select(Grievance.reference, Grievance.category, Grievance.status, Grievance.priority,
                   Grievance.station_id, Grievance.escalation_level, Grievance.created_at, Grievance.due_at,
                   Grievance.resolved_at, Grievance.closed_at)
            .where(*conditions).order_by(Grievance.created_at, Grievance.id).limit(limit)
        ).all()
        return header, [[r[0], r[1], r[2], r[3], station_codes.get(r[4]), *r[5:]] for r in rows]
    header = ["case_number", "template", "channel", "status", "attempts", "created_at", "sent_at", "delivered_at"]
    rows = db.execute(
        select(Case.case_number, Notification.template, Notification.channel, Notification.status,
               Notification.attempts, Notification.created_at, Notification.sent_at, Notification.delivered_at)
        .join(Case, Case.id == Notification.case_id)
        .where(*_case_scope(db, job), Notification.created_at >= period[0], Notification.created_at < period[1])
        .order_by(Notification.created_at, Notification.id).limit(limit)
    ).all()
    return header, [list(r) for r in rows]


def _render_csv(header: list[str], rows: list[list]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    for row in rows:
        writer.writerow([v.isoformat() if isinstance(v, datetime) else _cell(v) for v in row])
    return buffer.getvalue().encode("utf-8")


def run_queued(db: Session, storage: ObjectStorage, *, limit: int = 5) -> int:
    settings = get_settings()
    processed = 0
    for job_id in db.scalars(
        select(ReportJob.id).where(ReportJob.status == J.QUEUED).order_by(ReportJob.created_at).limit(limit)
    ).all():
        claimed = db.execute(
            update(ReportJob).where(ReportJob.id == job_id, ReportJob.status == J.QUEUED)
            .values(status=J.RUNNING, started_at=func.now()).returning(ReportJob.id)
        ).first()
        db.commit()
        if claimed is None:
            continue
        job = db.get(ReportJob, job_id, populate_existing=True)
        try:
            header, rows = _rows(db, job, settings.report_max_rows)
            body = _render_csv(header, rows)
            key = f"reports/{job.id}.csv"
            storage.put(key, body, content_type=CONTENT_TYPE, checksum_sha256=hashlib.sha256(body).hexdigest())
        except Exception as exc:  # noqa: BLE001
            db.rollback()
            job = db.get(ReportJob, job_id, populate_existing=True)
            job.status, job.error_code, job.completed_at = J.FAILED, type(exc).__name__[:64], utcnow()
            record_audit(db, action=AuditAction.REPORT_FAILED, entity_type="report_job", entity_id=job.id,
                         actor_user_id=None, after={"error": job.error_code})
            db.commit()
            logger.warning("Report generation failed", extra={"report_job": str(job.id), "error": job.error_code})
            continue
        now = utcnow()
        job.status, job.storage_key, job.row_count, job.size_bytes = J.COMPLETED, key, len(rows), len(body)
        job.completed_at, job.expires_at = now, now + timedelta(hours=settings.report_artifact_ttl_hours)
        record_audit(db, action=AuditAction.REPORT_GENERATED, entity_type="report_job", entity_id=job.id,
                     actor_user_id=None, after={"rows": len(rows), "truncated": len(rows) >= settings.report_max_rows})
        recipients = {job.requested_by_user_id}
        if job.schedule_id is not None:
            schedule = db.get(ReportSchedule, job.schedule_id)
            if schedule is not None:
                recipients |= {uuid.UUID(r) for r in schedule.recipient_user_ids}
        staff_notifications.notify(db, recipients, StaffNotificationKind.REPORT_READY,
                                   link=f"/reports/jobs/{job.id}", dedupe=str(job.id))
        db.commit()
        processed += 1
    return processed


def expire_artifacts(db: Session, storage: ObjectStorage, *, limit: int = 100) -> int:
    rows = list(
        db.scalars(
            select(ReportJob).where(ReportJob.status == J.COMPLETED, ReportJob.expires_at <= func.now()).limit(limit)
        )
    )
    for job in rows:
        if job.storage_key:
            storage.delete(job.storage_key)
        job.status = J.EXPIRED
    db.commit()
    return len(rows)


# --- Schedules -----------------------------------------------------------------------------------


def _next_run(cadence: ReportCadence, after: datetime) -> datetime:
    local = after.astimezone(CASE_NUMBER_TZ)
    start_of_next_day = datetime.combine(local.date() + timedelta(days=1), time(1, 0), tzinfo=CASE_NUMBER_TZ)
    if cadence is ReportCadence.DAILY:
        return start_of_next_day
    days_until_monday = (7 - local.weekday()) % 7 or 7
    return datetime.combine(local.date() + timedelta(days=days_until_monday), time(1, 0), tzinfo=CASE_NUMBER_TZ)


def _validate_recipients(db: Session, recipient_ids: list[uuid.UUID], station_id: uuid.UUID | None) -> None:
    for recipient_id in recipient_ids:
        user = db.get(User, recipient_id)
        if user is None or not user.is_active or not has_permission(user, Permission.REPORT_GENERATE):
            raise ValidationFailed("Recipients must be active staff who may view reports", code="invalid_recipient")
        if Role(user.role) is not Role.ADMIN and (station_id is None or user.station_id != station_id):
            raise ValidationFailed(
                "Non-administrator recipients require a schedule limited to their own station",
                code="invalid_recipient",
            )


def create_schedule(
    db: Session, actor: User, *, report_type: ReportType, cadence: ReportCadence, station_id: uuid.UUID | None,
    recipient_user_ids: list[uuid.UUID],
) -> ReportSchedule:
    require_permission(actor, Permission.REPORT_SCHEDULE)
    _validate_recipients(db, recipient_user_ids, station_id)
    schedule = ReportSchedule(
        id=uuid.uuid4(), report_type=report_type, cadence=cadence, station_id=station_id,
        recipient_user_ids=[str(r) for r in dict.fromkeys(recipient_user_ids)],
        next_run_at=_next_run(cadence, utcnow()), is_active=True, created_by_user_id=actor.id,
    )
    db.add(schedule)
    record_audit(db, action=AuditAction.REPORT_SCHEDULED, entity_type="report_schedule", entity_id=schedule.id,
                 actor_user_id=actor.id, after={"report_type": report_type, "cadence": cadence,
                                                "station_id": station_id, "recipients": len(recipient_user_ids)})
    db.commit()
    db.refresh(schedule)
    return schedule


def list_schedules(db: Session, actor: User) -> list[ReportSchedule]:
    require_permission(actor, Permission.REPORT_SCHEDULE)
    return list(db.scalars(select(ReportSchedule).order_by(ReportSchedule.created_at)))


def set_schedule_active(db: Session, actor: User, schedule_id: uuid.UUID, active: bool) -> ReportSchedule:
    require_permission(actor, Permission.REPORT_SCHEDULE)
    schedule = db.get(ReportSchedule, schedule_id)
    if schedule is None:
        raise NotFound("Schedule not found", code="report_schedule_not_found")
    schedule.is_active = active
    if active:
        schedule.next_run_at = _next_run(ReportCadence(schedule.cadence), utcnow())
    record_audit(db, action=AuditAction.REPORT_SCHEDULE_UPDATED, entity_type="report_schedule",
                 entity_id=schedule.id, actor_user_id=actor.id, after={"is_active": active})
    db.commit()
    db.refresh(schedule)
    return schedule


def run_due_schedules(db: Session, *, limit: int = 20) -> int:
    created = 0
    for schedule in db.scalars(
        select(ReportSchedule).where(ReportSchedule.is_active.is_(True), ReportSchedule.next_run_at <= func.now())
        .limit(limit).with_for_update(skip_locked=True)
    ).all():
        owner = db.get(User, schedule.created_by_user_id)
        period_to = datetime.combine(
            schedule.next_run_at.astimezone(CASE_NUMBER_TZ).date(), time.min, tzinfo=CASE_NUMBER_TZ
        )
        period_from = period_to - (timedelta(days=1) if schedule.cadence == ReportCadence.DAILY else timedelta(days=7))
        if owner is not None and owner.is_active:
            request_report(db, owner, report_type=ReportType(schedule.report_type), period_from=period_from,
                           period_to=period_to, station_id=schedule.station_id, schedule_id=schedule.id, commit=False)
            created += 1
        schedule.next_run_at = _next_run(ReportCadence(schedule.cadence), utcnow())
    db.commit()
    return created
